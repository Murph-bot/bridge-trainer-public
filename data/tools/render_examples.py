#!/usr/bin/env python3
"""Rewrites the worked-examples section of auction-to-constraints.md from examples/worked-examples.json."""
import json, os, re

ROOT = os.path.join(os.path.dirname(__file__), "..")
MARK = "## 5. Worked examples"
NOTES = {
    "ex1-1NT-3NT": "Uncontested NT game. North's 1NT denies 2♣/2NT hands (sibling negation). South's 3NT carries no 4-card major and denies Stayman, transfers, Gerber, Texas and quantitative 4NT. West's pass over 3NT has no rule in the user's system, so it adds nothing.",
    "ex2-1S-2S-4S": "North's simple raise (opponents' default: 6–10, 3–4 spades) is a cap: it denies the Jacoby 2NT, splinter and 4♠ hands. South's 4♠ rebid shows game values or shape.",
    "ex3-competitive-1H-2C-2H-P-4H": "Competitive. The user (East) overcalled 2♣ and is on lead against 4♥. South's 2♥ matched `cr.1H.2C.raise` and denies the negative double and the cue-bid limit raise (soft). North's 4♥ is unmatched and read naturally (own suit, nothing new). West's pass after 2♥ is unmodelled, so it adds nothing.",
    "ex4-1NT-Stayman-4H": "Stayman auction. North's 1NT then 2♥ = 4+♥. South's 2♣ keeps the Stayman disjunction. South's 4♥ is unmatched and read as a raise of partner's suit (3+♥). East's direct pass over 1NT matched the user's own `vs1n.direct.P` and denies the user's defence-to-1NT calls.",
    "ex5-weak2H-relay-same-system": "Option 'opponents play our system'. East's 1st-seat 2♥ = 5+♥ 6–11; the relay answer 3♦ = step 3 = minimum with 6♥. West's 2♠ relay needs HCP + heart length ≥ 18 and denies PMKC (soft). West's 4♥ is read as a raise.",
}


def compact(js):
    for _ in range(3):
        js = re.sub(r"\[\s*([^\[\]{}]*?)\s*\]", lambda m: "[" + re.sub(r"\s+", " ", m.group(1)).strip() + "]", js)
    return re.sub(r'"len": \{([^{}]*)\}', lambda m: '"len": {' + re.sub(r"\s+", " ", m.group(1)).strip() + "}", js)


md_path = os.path.join(ROOT, "auction-to-constraints.md")
md = open(md_path, encoding="utf-8").read()
head = md[:md.index(MARK)]
out = [MARK, "\n\nGenerated by `tools/ref_constraints.py` + `tools/render_examples.py`. The leader's seat is omitted (known hand). `hard` filters; `soft` penalises; `all` holds non-interval predicates; `notAnyFromSiblings` lists sibling rule ids whose `shows` the hand should not meet.\n"]
for e in json.load(open(os.path.join(ROOT, "examples", "worked-examples.json"), encoding="utf-8")):
    s = e["sampling"]
    out.append(f"\n### {e['id']}\n\nDealer {e['dealer']}. Auction: `{' '.join(e['auction'])}`. Leader {e['leader']} holds {e['leaderHand']}. "
               f"Profiles: {', '.join(f'{k}={v}' for k, v in e['profiles'].items())}.\n\n{NOTES[e['id']]}\n\n"
               f"Sampling (reference, naive shuffle): {s['accepted']} accepted of {s['tried']} tried, acceptance {s['acceptanceRate']*100:.2f}%, {s['seconds']} s.\n\n"
               f"```json\n{compact(json.dumps(e['constraints'], ensure_ascii=False, indent=1))}\n```\n")
open(md_path, "w", encoding="utf-8").write(head + "".join(out))
print("rendered")
